def _sessions(end: date, count: int) -> list[date]:
    """Weekday sessions ending at `end` (holidays are not modelled)."""
    days: list[date] = []
    d = end
    while len(days) < count:
        if d.weekday() < 5:
            days.append(d)
        d -= timedelta(days=1)
    days.reverse()
    return days


@lru_cache(maxsize=64)
def _generate(symbol: str, end: date, count: int) -> tuple[Bar, ...]:
    _, _, _, _, _, p0, mu, sigma = _BY_SYMBOL[symbol]
    mu *= 0.5  # keep the synthetic 5-year path in a plausible range
    rng = np.random.default_rng(zlib.crc32(symbol.encode()))
    n = count
    dt = 1 / 252
    # Mild volatility clustering via a slowly varying multiplier.
    regime = 1 + 0.35 * np.sin(np.linspace(0, 9 * np.pi, n) + rng.uniform(0, 6.28))
    shocks = rng.standard_normal(n)
    rets = (mu - 0.5 * sigma**2) * dt + sigma * np.sqrt(dt) * regime * shocks
    closes = p0 * np.exp(np.cumsum(rets))
    opens = np.empty(n)
    opens[0] = p0
    opens[1:] = closes[:-1] * (1 + rng.normal(0, sigma * 0.12 * np.sqrt(dt), n - 1))
    spread = np.abs(rng.normal(0, sigma * 0.45 * np.sqrt(dt), n)) * closes
    highs = np.maximum(opens, closes) + spread
    lows = np.maximum(np.minimum(opens, closes) - spread, 0.01)
    base_vol = 8e6 if _BY_SYMBOL[symbol][3] == "equity" else 3e7
    vols = (base_vol * (1 + 2.2 * np.abs(rets) / (sigma * np.sqrt(dt))) * rng.uniform(0.6, 1.4, n)).astype(int)
    sessions = _sessions(end, n)
    return tuple(
        Bar(
            day=sessions[i],
            open=round(float(opens[i]), 2),
            high=round(float(highs[i]), 2),
            low=round(float(lows[i]), 2),
            close=round(float(closes[i]), 2),
            adj_close=round(float(closes[i]), 2),  # synthetic series has no corporate actions
            volume=int(vols[i]),
        )
        for i in range(n)
    )


class MockProvider(MarketDataProvider):
    name = "mock"
    data_class = "simulated"

    def __init__(self, anchor: date, history_days: int = 1300) -> None:
        self.anchor = anchor
        self.history_days = history_days

    def instruments(self) -> list[Instrument]:
        return [
            Instrument(r[0], r[1], r[2], "USD", r[3], r[4]) for r in _UNIVERSE
        ]

    def history(self, symbol: str, start: date | None = None, end: date | None = None) -> list[Bar]:
        symbol = symbol.upper()
        if symbol not in _BY_SYMBOL:
            raise KeyError(symbol)
        bars = _generate(symbol, self.anchor, self.history_days)
        return [b for b in bars if (start is None or b.day >= start) and (end is None or b.day <= end)]
