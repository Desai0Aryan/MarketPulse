import { Badge } from "@/components/ui/primitives";
import type { ApiMeta } from "@/types/api";
import { fmtDay } from "@/lib/utils";

const LABEL: Record<ApiMeta["data_class"], string> = {
  live: "Live",
  delayed: "Delayed",
  historical: "Historical",
  simulated: "Simulated",
};

/** Provenance label: live / delayed / historical / simulated are always distinguishable. */
export function DataBadge({ meta, asOf }: { meta?: ApiMeta; asOf?: string }) {
  if (!meta) return null;
  const tone = meta.data_class === "simulated" ? "warn" : meta.data_class === "live" ? "up" : "accent";
  return (
    <span className="inline-flex items-center gap-2">
      <Badge tone={tone}>{LABEL[meta.data_class]}</Badge>
      {asOf && <span className="text-[11px] text-muted">as of {fmtDay(asOf)}</span>}
    </span>
  );
}

export function DemoBanner({ meta }: { meta?: ApiMeta }) {
  if (!meta?.demo) return null;
  return (
    <div role="note" className="mb-5 flex items-start gap-3 rounded-lg border border-warn/30 bg-warn/5 px-4 py-2.5 text-xs text-muted">
      <Badge tone="warn">Demo mode</Badge>
      <p>
        All prices on screen are <strong className="text-fg">synthetic</strong>, generated by a seeded simulator. They are not real market quotes.
        Index cards use ETFs as clearly labeled proxies.
      </p>
    </div>
  );
}
